function mm = eyelive_open(filename)
% EYELIVE_OPEN Opens a memory-mapped session file for reading the StateBlock.
%
% mm = eyelive_open('session.bin')
% returns a memmapfile object configured to read the 256-byte StateBlock
% at offset 256.

    mm = memmapfile(filename, ...
        'Offset', 256, ...
        'Repeat', 1, ...
        'Format', { ...
            'uint32', [1 1], 'magic'; ...
            'uint32', [1 1], 'version'; ...
            'uint64', [1 1], 'seq'; ...
            'double', [1 1], 't_last'; ...
            'single', [1 1], 'x'; ...
            'single', [1 1], 'y'; ...
            'single', [1 1], 'speed_deg_s'; ...
            'uint8',  [1 1], 'cls'; ...
            'uint8',  [1 1], 'in_event'; ...
            'uint16', [1 1], 'n_classes'; ...
            'uint64', [1 1], 'n_samples'; ...
            'uint64', [1 1], 'event_counter'; ...
            'uint64', [1 1], 'provisional_counter'; ...
            'double', [1 1], 'ev_t_onset'; ...
            'double', [1 1], 'ev_t_offset'; ...
            'single', [1 1], 'ev_amplitude_deg'; ...
            'single', [1 1], 'ev_peak_speed_deg_s'; ...
            'single', [1 1], 'ev_direction_rad'; ...
            'uint8',  [1 1], 'ev_cls'; ...
            'uint8',  [1 1], 'ev_provisional'; ...
            'uint16', [1 1], 'ev_pad'; ...
            'uint64', [1 1], 'ev_id'; ...
            'single', [1 1], 'pred_x'; ...
            'single', [1 1], 'pred_y'; ...
            'single', [1 1], 'pred_sigma_x'; ...
            'single', [1 1], 'pred_sigma_y'; ...
            'double', [1 1], 'pred_t_valid'; ...
            'uint8',  [1 1], 'pred_valid'; ...
            'uint8',  [1 3], 'pred_pad'; ...
            'uint32', [1 1], 'health_flags'; ...
            'uint32', [1 1], 'dropped_packets'; ...
            'single', [1 1], 'detect_latency_ms_p50'; ...
            'single', [1 1], 'detect_latency_ms_p95'; ...
            'double', [1 1], 'deg_per_unit'; ...
            'double', [1 1], 'rate_hz'; ...
            'uint8',  [1 88], 'reserved' ...
        });
end
